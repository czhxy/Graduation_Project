K.h2(doc, "（3）零样本分类 ≠ 训练出来的分类头")
K.p(doc, "CLIP 没有 softmax 分类层，也没有在本课题数据上训练过。它的分类方式是："
         "把图像编码成 768 维向量，把每个类别名（如“a photo of a waterbird.”）也编码成 768 维向量，"
         "两者算余弦相似度，取相似度高的类别。")
K.p(doc, "这个差别很重要：你抑制某个头之后，改变的是**图像向量**，"
         "不是某个分类器的权重。所以效果会通过相似度分布整体体现，而不是简单地“某类概率降低”。"
         "写实验分析时要按这个机制来解释现象。")

K.h2(doc, "（4）“相关”不等于“因果”")
K.p(doc, "头级评分高，只说明该头的输出与背景文本方向**相关**。"
         "真正支持“这个头在导致背景依赖”的证据，是**干预后指标改善**——"
         "这正是定向抑制与随机对照实验的意义所在。论文里要区分“归因证据”和“因果证据”，"
         "不要用评分高就直接断言因果。")

K.h2(doc, "（5）总体准确率 ≠ 模型好坏")
K.p(doc, "Waterbirds 里多数组占绝大多数，所以一个“只会按背景猜”的模型也能拿到很高的总体准确率。"
         "这就是任务书为什么要求你同时报告四组和**最差组**准确率。"
         "本文的核心指标应该是最差组准确率，总体准确率是用来衡量代价的。")

K.h2(doc, "（6）随机种子 ≠ 走过场")
K.p(doc, "随机抑制的结果本身有随机性（随机挑头、随机初始化影响数据顺序）。"
         "只跑一次得到的数字，可能比定向抑制高，也可能低，纯属运气。"
         "任务书要求“随机对照至少重复 3 次，报告均值和标准差”，"
         "这个要求必须严格执行，否则结论站不住。")

